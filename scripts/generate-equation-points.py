#!/usr/bin/env python3
"""
Writes src/lib/equation-points.ts: the equation on the hoodie, as a few
thousand points, for the homepage's closing beat (the scroll scene's cloud
condenses into it, mirroring the opening zoom).

The two lines are the ones on the hoodie in the portrait:

    L = -1/4 F_{mu nu} F^{mu nu}
      + i psi-bar D-slash psi

They are typeset here from a maths font (STIX, which ships with macOS) and not
read off the portrait, because the lettering there runs into the edge of the
sketch. Each point is stored as two 12-bit numbers across the equation's own
bounding box, packed as base64, so it is small and needs no work at load.

Run:  python3 scripts/generate-equation-points.py
Needs: Pillow, numpy, and the STIX fonts in /System/Library/Fonts/Supplemental.
"""
import base64
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

FONTS = Path("/System/Library/Fonts/Supplemental")
REG = str(FONTS / "STIXGeneral.otf")
ITAL = str(FONTS / "STIXGeneralItalic.otf")

SIZE = 260  # points per em at the working scale
THICK = 5  # stroke thickening, so thin strokes still catch points
TARGET = 4600  # about how many points to keep
OUT = Path(__file__).resolve().parent.parent / "src" / "lib" / "equation-points.ts"


def font(path, size):
    return ImageFont.truetype(path, int(size))


def main():
    W, H = 2200, 900
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)

    reg = font(REG, SIZE)
    ital = font(ITAL, SIZE)
    small = font(ITAL, SIZE * 0.55)
    tiny = font(REG, SIZE * 0.5)

    def text(x, y, s, f, thick=THICK):
        """Draw s with its baseline at y; return the x after it."""
        d.text((x, y), s, font=f, fill=255, anchor="ls", stroke_width=thick, stroke_fill=255)
        return x + f.getlength(s)

    # ---- line 1: L = -1/4 F_{mu nu} F^{mu nu}
    x, base = 60, 330
    x = text(x, base, "ℒ", reg) + 40  # script L
    x = text(x, base, "=", reg) + 50
    x = text(x, base, "−", reg) + 20  # minus
    # the fraction 1/4, drawn with its own bar
    fw = tiny.getlength("1") + 30
    d.text((x + fw / 2, base - 135), "1", font=tiny, fill=255, anchor="ms", stroke_width=THICK, stroke_fill=255)
    d.rectangle([x, base - 118, x + fw, base - 118 + THICK + 3], fill=255)
    d.text((x + fw / 2, base - 8), "4", font=tiny, fill=255, anchor="ms", stroke_width=THICK, stroke_fill=255)
    x += fw + 36
    # F with its lower indices, then F with its upper indices
    x = text(x, base, "F", ital)
    x = text(x + 6, base + 54, "μν", small) + 46
    x = text(x, base, "F", ital)
    x = text(x + 6, base - 124, "μν", small)

    # ---- line 2: + i psi-bar D-slash psi  (indented under the F's, as on the hoodie)
    x, base = 560, 700
    x = text(x, base, "+", reg) + 60
    x = text(x, base, "i", ital) + 36
    px = x
    x = text(x, base, "ψ", ital)
    # the bar over psi
    d.rectangle([px + 18, base - 205, x - 6, base - 205 + THICK + 4], fill=255)
    x += 40
    dx = x
    x = text(x, base, "D", ital)
    # the slash through D
    d.line([(dx + 16, base + 20), (x - 6, base - 190)], fill=255, width=THICK + 6)
    x += 36
    x = text(x, base, "ψ", ital)

    mask = np.array(img) > 127
    ys, xs = np.where(mask)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    mask = mask[y0 : y1 + 1, x0 : x1 + 1]
    h, w = mask.shape
    aspect = w / h

    # Sample the strokes on a jittered grid, spaced for about TARGET points.
    area = int(mask.sum())
    step = max(2.0, (area / TARGET) ** 0.5)
    rnd = random.Random(7)
    pts = []
    gy = 0.0
    while gy < h:
        gx = 0.0
        while gx < w:
            px_ = int(gx + rnd.random() * step * 0.8)
            py_ = int(gy + rnd.random() * step * 0.8)
            if 0 <= px_ < w and 0 <= py_ < h and mask[py_, px_]:
                pts.append((px_, py_))
            gx += step
        gy += step

    packed = bytearray()
    for px_, py_ in pts:
        qx = round(px_ / (w - 1) * 4095)
        qy = round(py_ / (h - 1) * 4095)
        packed += qx.to_bytes(2, "little") + qy.to_bytes(2, "little")

    ts = f"""/**
 * The equation on the hoodie, as points, for the homepage's closing beat.
 * Generated by scripts/generate-equation-points.py: edit that, not this.
 *
 * `data` is base64 of little-endian uint16 pairs (x, y), each 0..4095 across the
 * equation's bounding box. `aspect` is that box's width over its height.
 */
export const EQUATION = {{
  aspect: {aspect:.4f},
  count: {len(pts)},
  data: "{base64.b64encode(bytes(packed)).decode()}",
}};
"""
    OUT.write_text(ts)
    print(f"wrote {OUT}: {len(pts)} points, aspect {aspect:.3f}, {len(ts)} bytes")

    # A preview, for checking the shape by eye.
    prev = Image.new("L", (w // 2 + 20, h // 2 + 20), 255)
    pd = ImageDraw.Draw(prev)
    for px_, py_ in pts:
        pd.ellipse([px_ / 2 + 8, py_ / 2 + 8, px_ / 2 + 12, py_ / 2 + 12], fill=30)
    prev.save("/tmp/equation-preview.png")


if __name__ == "__main__":
    main()
