#!/usr/bin/env node
/**
 * Builds the land dots for the homepage globe.
 *
 * The globe is a dot-matrix Earth: points spread evenly over a sphere, kept
 * only where they fall on land. That is a build-time job — the browser gets a
 * short list of coordinates and does nothing but rotate and draw them, so the
 * page ships no map library and no geometry.
 *
 * Points come from a Fibonacci spiral, which spaces them evenly by area (a
 * plain latitude/longitude grid bunches up at the poles). Each one is tested
 * against Natural Earth's 1:110m land polygons.
 *
 *     npm install --no-save world-atlas topojson-client d3-geo
 *     node scripts/generate-globe-dots.mjs
 *
 * Writes src/lib/globe-dots.ts. The three packages are only needed to run this
 * script, so they are deliberately not in package.json.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const POINTS = 9000;
const GOLDEN = Math.PI * (3 - Math.sqrt(5));

const topology = JSON.parse(
  readFileSync("node_modules/world-atlas/land-110m.json", "utf8")
);
const land = feature(topology, topology.objects.land);

const dots = [];
for (let i = 0; i < POINTS; i++) {
  const lat = (Math.asin(1 - (2 * (i + 0.5)) / POINTS) * 180) / Math.PI;
  const lon = ((((i * GOLDEN * 180) / Math.PI) % 360) + 540) % 360 - 180;
  // Antarctica is a white wedge that adds nothing to a story about operating
  // across four countries, and crowds the bottom of the globe.
  if (lat < -58) continue;
  if (geoContains(land, [lon, lat])) {
    dots.push(Math.round(lat * 10), Math.round(lon * 10));
  }
}

const rows = [];
for (let i = 0; i < dots.length; i += 24) {
  rows.push("  " + dots.slice(i, i + 24).join(", ") + ",");
}

writeFileSync(
  "src/lib/globe-dots.ts",
  `/**
 * Land dots for the homepage globe: a flat list of [latitude, longitude]
 * pairs, each in tenths of a degree. Generated by
 * scripts/generate-globe-dots.mjs — edit that, not this.
 */
export const LAND: number[] = [
${rows.join("\n")}
];
`
);
console.log(`${dots.length / 2} land dots written to src/lib/globe-dots.ts`);
