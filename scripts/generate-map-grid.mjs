#!/usr/bin/env node
/**
 * Builds the land bitmap for the homepage atlas.
 *
 * The atlas is a flat, dot-matrix world map that scrolls sideways like the
 * message board of an old display. Unlike the globe's Fibonacci spiral, a flat
 * map wants a regular grid: every dot sits on a lat/lon cell, so the rows line
 * up the way LEDs on a panel do.
 *
 * Each cell is tested against Natural Earth's 1:110m land polygons and stored
 * as one bit. The browser gets ~3 KB of base64 and draws it; no map library,
 * no geometry on the page.
 *
 *     npm install --no-save world-atlas topojson-client d3-geo
 *     node scripts/generate-map-grid.mjs
 *
 * Writes src/lib/map-grid.ts. The three packages are only needed to run this
 * script, so they are deliberately not in package.json.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

/** Degrees per cell. 1.5 gives 240 columns, which reads as a fine LED panel. */
const STEP = 1.5;
const LAT_TOP = 84; // Greenland's northern tip is ~83.6
const LAT_BOTTOM = -58; // Antarctica adds nothing to this story

const COLS = Math.round(360 / STEP);
const ROWS = Math.round((LAT_TOP - LAT_BOTTOM) / STEP);

const topology = JSON.parse(
  readFileSync("node_modules/world-atlas/land-110m.json", "utf8")
);
const land = feature(topology, topology.objects.land);

const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let lit = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = LAT_TOP - (r + 0.5) * STEP;
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5) * STEP;
    if (geoContains(land, [lon, lat])) {
      const i = r * COLS + c;
      bits[i >> 3] |= 1 << (i & 7);
      lit++;
    }
  }
}

writeFileSync(
  "src/lib/map-grid.ts",
  `/**
 * Land bitmap for the homepage atlas. One bit per ${STEP}-degree cell, row-major
 * from the north-west corner, least-significant bit first, base64.
 * Generated by scripts/generate-map-grid.mjs — edit that, not this.
 */
export const MAP_GRID = {
  cols: ${COLS},
  rows: ${ROWS},
  step: ${STEP},
  latTop: ${LAT_TOP},
  lonLeft: -180,
  bits: "${Buffer.from(bits).toString("base64")}",
} as const;
`
);
console.log(`${lit} land cells of ${COLS * ROWS} written to src/lib/map-grid.ts`);
